type ScienceTemplate = {
  templateId: string
  keywords: string[]
  build: (context: LessonContext) => LessonContent
}

const findBestTemplate = (text: string, templates: ScienceTemplate[]) => {
  let best: ScienceTemplate | undefined
  let bestKeywordLength = 0

  for (const template of templates) {
    const keywordLength = template.keywords.reduce(
      (longest, keyword) => (text.includes(keyword) ? Math.max(longest, keyword.length) : longest),
      0,
    )
    if (keywordLength > bestKeywordLength) {
      best = template
      bestKeywordLength = keywordLength
    }
  }

  return best
}

