function buildFocusedLesson(context: LessonContext, spec: FocusedLessonSpec): LessonContent {
  const { teachingPoint, ...content } = spec
  return {
    ...content,
    guidingQuestion: `学习“${context.title}”时，怎样把概念条件、推理过程和可检验结论连接起来？`,
    core: `“${context.title}”的教学落点是：${teachingPoint}。`,
  }
}

function topicFamilyId(subjectId: SubjectId, title: string): string {
  const rules = scienceTopicFamilies[subjectId] ?? []
  let bestId = 'general'
  let bestLength = 0
  for (const rule of rules) {
    const length = rule.keywords.reduce(
      (longest, keyword) => (title.includes(keyword) ? Math.max(longest, keyword.length) : longest),
      0,
    )
    if (length > bestLength) {
      bestId = rule.id
      bestLength = length
    }
  }
  return bestId
}

function personalizeLesson(subjectId: SubjectId, context: LessonContext, lesson: LessonContent): LessonContent {
  const familyId = topicFamilyId(subjectId, context.title)
  return {
    ...lesson,
    templateId: `${lesson.templateId}:${familyId}`,
    core: `“${context.title}”需要掌握的概念落点如下。${lesson.core}`,
  }
}

export function buildScienceLesson(subjectId: SubjectId, context: LessonContext): LessonContent | undefined {
  if (subjectId !== 'math' && subjectId !== 'physics' && subjectId !== 'chemistry') return undefined

  const regressionTemplateId = scienceLessonRegressionMap[context.title]
  if (regressionTemplateId) {
    const focusedSpec = focusedLessonSpecs[regressionTemplateId]
    if (focusedSpec) return buildFocusedLesson(context, focusedSpec)
  }

  const templates = templateGroups[subjectId] ?? []
  const titleMatch = findBestTemplate(context.title, templates)
  if (titleMatch) return personalizeLesson(subjectId, context, titleMatch.build(context))

  const unitMatch = findBestTemplate(context.unitTitle, templates)
  if (unitMatch) return personalizeLesson(subjectId, context, unitMatch.build(context))

  return personalizeLesson(subjectId, context, fallbackLessons[subjectId](context))
}
