function buildTopicTeachingTarget(templateId: string, context: LessonContext): string {
  const subjectFallback = templateId.startsWith('biology-')
    ? '把结构、过程、条件和实验或材料证据对应起来'
    : templateId.startsWith('geography-')
      ? '固定空间尺度和时间条件，用过程解释区域差异'
      : '明确输入、状态、输出、测试和风险边界'
  const target = teachingTargetByTemplate[templateId] ?? subjectFallback
  return `落实到“${context.title}”时，应${target}。`
}

function resolveTemplate(subjectId: SubjectId, templates: LessonTemplate[], context: LessonContext): LessonTemplate | undefined {
  const explicitId = APPLIED_LESSON_TEMPLATE_REGRESSIONS[`${subjectId}:${context.title}`]
  if (explicitId) {
    const explicitTemplate = templates.find((template) => template.templateId === explicitId)
    if (!explicitTemplate) throw new Error(`Missing explicit lesson template: ${explicitId}`)
    return explicitTemplate
  }
  return findTemplate(templates, context)
}

export function buildAppliedLesson(subjectId: SubjectId, context: LessonContext): LessonContent | undefined {
  if (subjectId === 'biology') {
    return materialize(resolveTemplate(subjectId, biologyTemplates, context) ?? biologyFallback, context)
  }
  if (subjectId === 'geography') {
    return materialize(resolveTemplate(subjectId, geographyTemplates, context) ?? geographyFallback, context)
  }
  if (subjectId === 'information') {
    return materialize(resolveTemplate(subjectId, informationTemplates, context) ?? informationFallback, context)
  }
  return undefined
}
