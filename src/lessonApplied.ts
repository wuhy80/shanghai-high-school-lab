import type { SubjectId } from './data'
import type { LessonContent, LessonContext, LessonStep } from './lessonTypes'

type LessonTemplate = {
  templateId: string
  keywords: string[]
  guidingQuestion: string
  core: string
  explanation: [string, string]
  steps: [LessonStep, LessonStep, LessonStep]
  example: LessonContent['example']
  selfCheck: LessonContent['selfCheck']
  pitfall: string
}

const S = (label: string, detail: string): LessonStep => ({ label, detail })

function materialize(template: LessonTemplate, context: LessonContext): LessonContent {
  const fill = (text: string) => text
    .replaceAll('{title}', context.title)
    .replaceAll('{unit}', context.unitTitle)
    .replaceAll('{focus}', context.unitFocus)
  const topicTarget = buildTopicTeachingTarget(template.templateId, context)

  return {
    templateId: template.templateId,
    guidingQuestion: fill(template.guidingQuestion),
    core: `${fill(template.core)} ${topicTarget}`,
    explanation: [fill(template.explanation[0]), fill(template.explanation[1])],
    steps: template.steps.map((step) => ({ label: fill(step.label), detail: fill(step.detail) })) as LessonContent['steps'],
    example: {
      prompt: fill(template.example.prompt),
      reasoning: [fill(template.example.reasoning[0]), fill(template.example.reasoning[1])],
      result: fill(template.example.result),
    },
    selfCheck: {
      question: fill(template.selfCheck.question),
      answer: fill(template.selfCheck.answer),
    },
    pitfall: fill(template.pitfall),
  }
}

function findTemplate(templates: LessonTemplate[], context: LessonContext) {
  const title = context.title.toLowerCase()
  const unit = `${context.unitTitle} ${context.unitFocus}`.toLowerCase()
  let best: { template: LessonTemplate, score: number } | undefined

  for (const template of templates) {
    let score = 0
    for (const rawKeyword of template.keywords) {
      const keyword = rawKeyword.toLowerCase()
      if (title.includes(keyword)) score = Math.max(score, 100 + keyword.length)
      else if (unit.includes(keyword)) score = Math.max(score, 10 + keyword.length)
    }
    if (score > 0 && (!best || score > best.score)) best = { template, score }
  }

  return best?.template
}

