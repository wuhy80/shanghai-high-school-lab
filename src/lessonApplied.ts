type TemplateVariantSpec = {
  templateId: string
  keywords: string[]
  guidingQuestion: string
  core: string
  explanation: [string, string]
  example: LessonContent['example']
  selfCheck: LessonContent['selfCheck']
  pitfall: string
  steps?: [LessonStep, LessonStep, LessonStep]
}

function variant(templates: LessonTemplate[], baseId: string, spec: TemplateVariantSpec): LessonTemplate {
  const base = templates.find((template) => template.templateId === baseId)
  if (!base) throw new Error(`Missing base lesson template: ${baseId}`)
  return { ...base, ...spec, steps: spec.steps ?? base.steps }
}

