function stableTopicSuffix(context: LessonContext) {
  let hash = 0
  for (const character of `${context.unitTitle}|${context.title}`) hash = (hash * 31 + character.charCodeAt(0)) >>> 0
  return hash.toString(36)
}

function advancedMathFamily(context: LessonContext) {
  const content = `${context.unitTitle} ${context.unitFocus} ${context.title}`
  const modelingUnit = /模型|建模|报告|方案/.test(context.unitFocus)
    && /红绿灯|优惠券|安全隐患|雨中行|出租车|家具搬运|登山|包装|菠萝|高度测量|外卖|附录|刹车|易拉罐|珠穆朗玛|水葫芦|铅球|电梯|存款|民生|照明/.test(context.unitTitle)
  if (modelingUnit) return advancedMathFamilies.modeling
  if (/导数|瞬时变化率|切线斜率|驻点/.test(content)) return advancedMathFamilies.derivative
  if (/条件概率|全概率|贝叶斯|后验概率/.test(`${context.unitTitle} ${context.title}`)) return advancedMathFamilies.conditionalProbability
  if (/随机变量|分布列|二项分布|正态分布|超几何|期望|方差/.test(content)) return advancedMathFamilies.distribution
  if (/计数|排列|组合|二项式|杨辉|乘法原理|加法原理/.test(content)) return advancedMathFamilies.counting
  if (/统计|抽样|样本|总体|估计|检验|相关|回归|频数|直方图|箱线图|数据/.test(content)) return advancedMathFamilies.statistics
  if (/概率|随机|事件|样本空间|频率|独立/.test(content)) return advancedMathFamilies.probability
  if (/坐标平面上的直线|倾斜角|斜率|直线方程|点到直线|两直线|平行直线/.test(content)) return advancedMathFamilies.lineGeometry
  if (/异面|直线与平面|平面与平面|二面角|线面角|空间距离|公垂线/.test(context.title)) return advancedMathFamilies.solid
  if (/向量|数量积|基底|共线|法向量/.test(content)) return advancedMathFamilies.vector
  if (/柱体|锥体|多面体|旋转体|球|表面积|体积|截面|母线/.test(content)) return advancedMathFamilies.solidMeasure
  if (/立体|空间|确定平面|相交平面|直线与平面|平面与平面|棱柱|棱锥|圆柱|圆锥|二面角|线面|异面/.test(content) && !/平面向量|复平面/.test(content)) return advancedMathFamilies.solid
  if (/圆锥曲线|椭圆|双曲线|抛物线|焦点|准线|离心率|轨迹方程|极坐标/.test(content)) return advancedMathFamilies.conic
  if (/直线|圆锥|轨迹|解析几何/.test(content)) return advancedMathFamilies.analytic
  if (/复数|虚数|共轭|辐角|棣莫弗/.test(content)) return advancedMathFamilies.complex
  if (/数列|递推|等差|等比|前.?项和|求和|数学归纳/.test(content)) return advancedMathFamilies.sequence
  if (/解三角形|正弦定理|余弦定理|三角形面积|仰角|俯角|方位角|三角测量/.test(content)) return advancedMathFamilies.triangleSolving
  if (/三角函数|正弦函数|余弦函数|正切函数|振幅|角频率|初相|相位|周期现象/.test(content)) return advancedMathFamilies.trigonometricFunction
  if (/三角|正弦|余弦|正切|弧度|周期|相位|仰角|俯角/.test(content)) return advancedMathFamilies.trigonometry
  if (/建模|模型|报告|样例|调查|方案|测量|误差|残差|评价指标|安全隐患|运价|优惠券|环保/.test(content)) return advancedMathFamilies.modeling
  return advancedMathFamilies.function
}

function buildAdvancedMathLesson(context: LessonContext): LessonContent {
  const family = advancedMathFamily(context)
  const topicBridge = `在“${context.unitTitle}”中，${context.title}承担的具体任务是：${context.unitFocus}`
  return {
    templateId: `${family.id}--${stableTopicSuffix(context)}`,
    guidingQuestion: `${context.title}：${family.question}`,
    core: `${context.title}不是一个孤立公式。${family.core}`,
    explanation: [`${topicBridge} ${family.explanation[0]}`, family.explanation[1]],
    steps: family.steps,
    example: family.example,
    selfCheck: family.selfCheck,
    pitfall: `${context.title}中尤其要注意：${family.pitfall}`,
  }
}

export function buildMathLesson(context: LessonContext): LessonContent | undefined {
  const matched = g10Term1MathLessons[context.title]
  if (!matched) return buildAdvancedMathLesson(context)
  return matched.core.includes(context.title)
    ? matched
    : { ...matched, core: `${context.title}：${matched.core}` }
}
